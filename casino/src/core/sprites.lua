-- Create GPU Image objects with crisp nearest-neighbor sampling
function sprites.init()
    if not love or not love.image or not love.graphics then return end
    
    for name, def in pairs(rectDefs) do
        local imgData = love.image.newImageData(def.w, def.h)
        for _, r in ipairs(def.rects) do
            local rx, ry, rw, rh, col = r[1], r[2], r[3], r[4], r[5]
            for py = ry, math.min(def.h - 1, ry + rh - 1) do
                for px = rx, math.min(def.w - 1, rx + rw - 1) do
                    imgData:setPixel(px, py, col[1], col[2], col[3], 1)
                end
            end
        end
        local img = love.graphics.newImage(imgData)
        img:setFilter("nearest", "nearest")
        images[name] = { img = img, w = def.w, h = def.h }
    end
end

-- Draw a pixel-art sprite centered at (cx, cy) scaled to targetSize
function sprites.draw(name, cx, cy, targetSize, alpha)
    local data = images[name]
    if not data then return end
    
    targetSize = targetSize or data.w
    alpha = alpha or 1
    local scale = targetSize / data.w
    
    love.graphics.setColor(1, 1, 1, alpha)
    love.graphics.draw(data.img, cx, cy, 0, scale, scale, data.w / 2, data.h / 2)
end

-- Fallback check in case init wasn't called before first draw
function sprites.get(name)
    if not images[name] then sprites.init() end
    return images[name]
end

return sprites
